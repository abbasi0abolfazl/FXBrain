@app.post("/api/auth/login", response_model=LoginResponse)
async def login(request: LoginRequest):
    """
    Authenticate user and return JWT token.
    
    Args:
        request: Login credentials
        
    Returns:
        LoginResponse: JWT token and user data
        
    Raises:
        HTTPException: 401 if credentials invalid, 403 if account inactive
    """
    user = next((u for u in sample_data.users if u["email"] == request.email), None)
    
    if not user or user["password"] != request.password:
        raise HTTPException(status_code=401, detail="ایمیل یا رمز عبور اشتباه است")
    
    if not user["is_active"]:
        raise HTTPException(status_code=403, detail="حساب کاربری غیرفعال است")
    
    # Generate JWT token
    token_data = {
        "sub": str(user["id"]),
        "email": user["email"],
        "role": user["role"],
        "exp": datetime.utcnow() + timedelta(days=7)
    }
    
    token = jwt.encode(token_data, SECRET_KEY, algorithm=ALGORITHM)
    
    # Remove password from response
    user_response = {k: v for k, v in user.items() if k != "password"}
    
    return LoginResponse(
        token=token,
        user=user_response,
        message="ورود موفقیت‌آمیز بود"
    )


